drop table if exists keluarga           cascade;
drop table if exists jarak_kantor       cascade;

-- 1. JARAK KANTOR (jalur darat; syarat SPPD >= 100 km)
create table jarak_kantor (
  kantor_a   text not null references kantor(kode),
  kantor_b   text not null references kantor(kode),
  jarak_km   numeric(7,1) not null check (jarak_km > 0),   -- rute mobil tercepat
  sumber     text not null,
  dicek_pada timestamptz not null,                          -- kapan jarak terakhir dicek
  primary key (kantor_a, kantor_b),
  check (kantor_a < kantor_b)                               -- satu baris per pasangan, urut abjad
);

-- 2. KELUARGA (anggota keluarga sesuai Kartu Keluarga)
create table keluarga (
  id            bigint generated by default as identity primary key,
  npp           text not null references karyawan(npp),
  nik           text not null unique check (nik ~ '^[0-9]{16}$'),   -- tidak boleh dobel
  nama          text not null,
  hubungan      text not null check (hubungan in ('Suami','Istri','Anak')),
  tanggal_lahir date not null                                       -- cek usia anak < 25 tahun
);

-- 3. PENGAJUAN KELUARGA (anggota yang diikutkan + hasil cek usia)
create table pengajuan_keluarga (
  id                  bigint generated by default as identity primary key,
  pengajuan_id        bigint not null references pengajuan_sppd(id) on delete cascade,
  keluarga_id         bigint not null references keluarga(id),
  usia_saat_pengajuan int  not null check (usia_saat_pengajuan >= 0),
  status              text not null check (status in ('Diterima','Ditolak')),
  alasan_tolak        text,
  unique (pengajuan_id, keluarga_id),
  check (status <> 'Ditolak' or alasan_tolak is not null)           -- wajib jika Ditolak
);

-- 4. NOTIFIKASI
create table notifikasi (
  id           bigint generated by default as identity primary key,
  penerima_npp text not null references karyawan(npp),
  judul        text not null,
  pesan        text not null,
  referensi    text,                                  -- no pengajuan / TPP / SK, untuk tombol 'Lihat'
  dibaca       boolean not null default false,
  dibuat_pada  timestamptz not null default now()
);

-- 5. RIWAYAT STATUS (audit trail)
create table riwayat_status (
  id          bigint generated by default as identity primary key,
  objek       text not null check (objek in ('pengajuan_sppd','tiket_pp','rab')),
  objek_id    bigint not null,                        -- id di tabel objek
  status_lama text,
  status_baru text not null,
  oleh_npp    text not null references karyawan(npp),
  waktu       timestamptz not null default now(),
  catatan     text
);

