-- ---------- TABEL HAK (TARIF) ----------
-- Tarif lama tidak dihapus: pakai berlaku_mulai / berlaku_sampai (kosong = masih berlaku)

-- 1. TARIF UANG HARIAN (tunjangan perjalanan dinas per orang per hari)
create table tarif_uang_harian (
  id              bigint generated by default as identity primary key,
  level_kelompok  text   not null check (level_kelompok in ('1/2/3','4','5','6/7','8/9')),
  kelas_hotel     text   not null,
  uang_makan      bigint not null check (uang_makan >= 0),
  uang_saku       bigint not null check (uang_saku >= 0),
  jumlah_per_hari bigint generated always as (uang_makan + uang_saku) stored,   -- dihitung otomatis
  berlaku_mulai   date   not null,
  berlaku_sampai  date,
  dasar_aturan    text   not null,                                              -- no. Keputusan Direksi
  check (berlaku_sampai is null or berlaku_sampai >= berlaku_mulai)
);

-- 2. TARIF PENGINAPAN (bantuan penginapan sementara)
create table tarif_penginapan (
  id             bigint generated by default as identity primary key,
  level_kelompok text   not null check (level_kelompok in ('1/2/3','4','5','6/7','8/9')),
  jumlah_orang   text   not null check (jumlah_orang in ('1','2','3-4','5 atau lebih')),   -- termasuk karyawan
  nominal        bigint not null check (nominal >= 0),
  berlaku_mulai  date   not null,
  berlaku_sampai date,
  check (berlaku_sampai is null or berlaku_sampai >= berlaku_mulai)
);

-- 3. TARIF SEWA RUMAH (1 tahun)
create table tarif_sewa (
  id             bigint generated by default as identity primary key,
  level_kelompok text   not null check (level_kelompok in ('1/2/3','4','5','6/7','8/9')),
  nominal        bigint not null check (nominal >= 0),
  berlaku_mulai  date   not null,
  berlaku_sampai date,
  check (berlaku_sampai is null or berlaku_sampai >= berlaku_mulai)
);

-- 4. TARIF PENGEPAKAN (saat ini baru asal Jabotabek; asal lain diisi manual HCIS)
create table tarif_pengepakan (
  id             bigint generated by default as identity primary key,
  level_kelompok text   not null check (level_kelompok in ('1/2/3','4','5','6/7','8/9')),
  jumlah_orang   text   not null check (jumlah_orang in ('1','2','3-4','5 atau lebih')),
  wilayah_asal   text   not null check (wilayah_asal in ('Jabotabek','Jawa Barat','Jawa Tengah dan DIY','Jawa Timur','Sumatera / Kalimantan / Sulawesi','Bali')),
  wilayah_tujuan text   not null check (wilayah_tujuan in ('Jabotabek','Jawa Barat','Jawa Tengah dan DIY','Jawa Timur','Sumatera / Kalimantan / Sulawesi','Bali')),
  nominal        bigint not null check (nominal >= 0),
  berlaku_mulai  date   not null
);

-- ---------- TRANSAKSI ----------

-- 5. TIKET PP (hanya untuk SPPD yang tidak membawa keluarga; dicek aplikasi)
create table tiket_pp (
  id             bigint generated by default as identity primary key,
  no_tpp         text   not null unique check (no_tpp ~ '^TPP-[0-9]{4}-[0-9]{5}$'),
  pengajuan_id   bigint not null references pengajuan_sppd(id) on delete cascade,
  skema          text   not null check (skema in ('dipesankan_kantor','reimburse')),
  asal           text   not null references kantor(kode),       -- selalu kantor baru (tujuan SK)
  tujuan         text   not null,                               -- kampung halaman karyawan
  tgl_pergi      date   not null,
  jam_pergi      time,
  tgl_pulang     date   not null,
  jam_pulang     time,
  nominal_pergi  bigint check (nominal_pergi >= 0),
  nominal_pulang bigint check (nominal_pulang >= 0),
  status         text   not null default 'Diajukan' check (status in ('Diajukan','Diproses','Selesai','Ditolak')),
  diajukan_pada  date   not null default current_date,
  check (tgl_pulang >= tgl_pergi),
  check (skema <> 'dipesankan_kantor' or jam_pergi is not null),                           -- jam wajib (skema kantor)
  check (skema <> 'reimburse' or (nominal_pergi is not null and nominal_pulang is not null)) -- nominal wajib (reimburse)
);

-- 6. RAB (angka tarif disimpan sebagai salinan/snapshot saat RAB dibuat)
create table rab (
  id                bigint generated by default as identity primary key,
  no_rab            text   not null unique,
  pengajuan_id      bigint not null unique references pengajuan_sppd(id) on delete cascade,   -- 1 pengajuan = 1 RAB aktif
  level_kelompok    text   not null check (level_kelompok in ('1/2/3','4','5','6/7','8/9')),
  jumlah_orang      int    not null check (jumlah_orang >= 1),     -- karyawan + keluarga yang Diterima
  jumlah_hari       int    not null default 5 check (jumlah_hari > 0),
  tarif_harian      bigint not null check (tarif_harian >= 0),
  uang_harian       bigint generated always as (jumlah_orang * jumlah_hari * tarif_harian) stored,
  pengepakan        bigint not null check (pengepakan >= 0),
  pengepakan_manual boolean not null default false,
  sewa              bigint not null check (sewa >= 0),
  penginapan        bigint not null check (penginapan >= 0),
  bantuan_sekolah   bigint not null default 0 check (bantuan_sekolah >= 0),
  total             bigint generated always as
                    (jumlah_orang * jumlah_hari * tarif_harian + pengepakan + sewa + penginapan + bantuan_sekolah) stored,
  pajak             bigint generated always as
                    (round((jumlah_orang * jumlah_hari * tarif_harian + pengepakan + sewa + penginapan + bantuan_sekolah) * 0.05)) stored,
  diterima          bigint generated always as
                    ((jumlah_orang * jumlah_hari * tarif_harian + pengepakan + sewa + penginapan + bantuan_sekolah)
                     - round((jumlah_orang * jumlah_hari * tarif_harian + pengepakan + sewa + penginapan + bantuan_sekolah) * 0.05)) stored,
  catatan           text,
  dibuat_oleh       text   not null references karyawan(npp),
  dibuat_pada       timestamptz not null default now()
);

-- 7. CHECKLIST KELENGKAPAN (hasil cek dokumen oleh HCIS)
create table checklist_kelengkapan (
  id           bigint generated by default as identity primary key,
  pengajuan_id bigint not null references pengajuan_sppd(id) on delete cascade,
  item         text   not null check (item in ('form','sk','kk','rekening','sekolah_asal','sekolah_baru')),
  wajib        boolean not null,
  hasil        text   not null check (hasil in ('Lengkap','Tidak lengkap','Tidak berlaku')),
  catatan      text,
  dicek_oleh   text   not null references karyawan(npp),
  dicek_pada   timestamptz not null default now(),
  unique (pengajuan_id, item)
);

