-- Bersihkan versi lama (aman: isinya hanya data dummy)
drop table if exists dokumen        cascade;
drop table if exists pengajuan_sppd cascade;
drop table if exists sk_mutasi      cascade;
drop table if exists karyawan       cascade;
drop table if exists kantor         cascade;

-- 0. KANTOR (master; di Excel Tahap 2, dibuat sekarang karena jadi relasi)
create table kantor (
  kode     text primary key,
  nama     text not null,
  kota     text not null,
  wilayah  text not null
           check (wilayah in ('Jabotabek','Jawa Barat','Jawa Tengah dan DIY','Jawa Timur',
                              'Sumatera / Kalimantan / Sulawesi','Bali')),
  alamat   text
);

-- 1. KARYAWAN (master, nantinya dari HRIS/SAP)
create table karyawan (
  npp                 text primary key check (npp ~ '^[0-9]{5}$'),
  nama                text not null,
  unit                text not null,
  jabatan             text not null,
  level               text not null check (level ~ '^[1-9]$'),
  grade               text,
  kantor_kode         text not null references kantor(kode),
  kampung_halaman     text,              -- rute Tiket PP; tidak bisa diubah karyawan
  no_rekening_payroll text               -- hanya dibaca ATA
);

-- 2. SK MUTASI (master, nantinya dari sistem SK)
create table sk_mutasi (
  no_sk           text primary key,
  npp             text not null references karyawan(npp),
  tanggal_sk      date not null,
  tanggal_efektif date not null,
  kantor_asal     text not null references kantor(kode),
  kantor_tujuan   text not null references kantor(kode),
  jabatan_lama    text not null,
  jabatan_baru    text not null,
  file_sk         text,                  -- path file di storage
  check (kantor_tujuan <> kantor_asal)
);

-- 3. PENGAJUAN SPPD (transaksi karyawan)
create table pengajuan_sppd (
  id              bigint generated by default as identity primary key,
  no_pengajuan    text not null unique check (no_pengajuan ~ '^SPPD-MTS-[0-9]{4}-[0-9]{5}$'),
  npp             text not null references karyawan(npp),
  no_sk           text not null unique references sk_mutasi(no_sk),   -- 1 SK = 1 pengajuan
  jarak_km        numeric(7,1) not null check (jarak_km >= 100),      -- disalin dari jarak_kantor
  bawa_keluarga   boolean not null,                                   -- tidak → berhak Tiket PP
  bantuan_sekolah boolean not null,                                   -- ya → dokumen sekolah wajib
  status          text not null default 'Draft'
                  check (status in ('Draft','Diajukan','Verifikasi HCS',
                                    'Proses Accounting & Tax','Selesai','Ditolak')),
  tahap_hcis      text not null default 'Diterima'
                  check (tahap_hcis in ('Diterima','Cek kelengkapan','Susun RAB',
                                        'Approval Dept Head HCIS','Buat PR',
                                        'Approval OAD & Group Head','Buat PO & GR',
                                        'Serahkan ke ATA','Diserahkan ke ATA')),
  diajukan_pada   date,                                               -- kosong selama Draft
  batas_tpp       date generated always as (
                    case when not bawa_keluarga then diajukan_pada + 7 end
                  ) stored,                                           -- diajukan_pada + 7 hari
  catatan         text
);

-- 4. DOKUMEN (hanya menyimpan link file; filenya di Supabase Storage)
create table dokumen (
  id            bigint generated by default as identity primary key,
  pengajuan_id  bigint references pengajuan_sppd(id) on delete cascade,
  tpp_id        bigint,   -- FK ke tiket_pp(id) ditambahkan di Tahap 3 (tabel belum ada)
  jenis         text not null
                check (jenis in ('sk','kk','rekening','sekolah_asal','sekolah_baru',
                                 'tiket','bukti_transaksi')),
  nama_file     text not null,
  tipe_file     text not null check (tipe_file in ('PDF','JPG','PNG')),
  ukuran_kb     int  not null check (ukuran_kb > 0 and ukuran_kb <= 10240),   -- maks 10 MB
  path_storage  text not null,
  diunggah_pada timestamptz not null default now(),
  check ((pengajuan_id is null) <> (tpp_id is null))   -- isi salah satu
);

