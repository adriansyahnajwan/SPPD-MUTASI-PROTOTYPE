-- ============================================================
-- AKSES (KHUSUS PROTOTIPE, DATA DUMMY)
-- RLS dinyalakan, tapi sementara semua orang dengan link boleh baca/tulis.
-- Nanti di Tahap 4 (login), aturan ini diganti: karyawan hanya lihat datanya sendiri,
-- HCIS boleh lihat semua. Role login ada di tabel akun (Tahap 4), bukan di karyawan.
-- ============================================================
alter table kantor         enable row level security;
alter table karyawan       enable row level security;
alter table sk_mutasi      enable row level security;
alter table pengajuan_sppd enable row level security;
alter table dokumen        enable row level security;

create policy "proto baca kantor"   on kantor         for select using (true);
create policy "proto baca karyawan" on karyawan       for select using (true);
create policy "proto baca sk"       on sk_mutasi      for select using (true);
create policy "proto akses sppd"    on pengajuan_sppd for all    using (true) with check (true);
create policy "proto akses dokumen" on dokumen        for all    using (true) with check (true);

-- Izin tabel untuk publishable/anon key (project Supabase baru tidak memberi otomatis)
