-- ---------- 1. TABEL ----------

-- AKUN: role & status akun. Password TIDAK disimpan di sini: Supabase Auth menyimpannya
-- terenkripsi di auth.users (pengganti kolom password_hash di rancangan Excel).
create table akun (
  npp            text primary key references karyawan(npp),        -- satu karyawan satu akun
  role           text not null check (role in ('karyawan','hcis','dept_head_hcis','oad','group_head','ata')),
  aktif          boolean not null default true,
  login_terakhir timestamptz
);

-- APPROVAL: jejak persetujuan RAB (Dept Head HCIS) dan PR (OAD lalu Group Head)
create table approval (
  id           bigint generated by default as identity primary key,
  objek        text not null check (objek in ('RAB','PR')),
  objek_no     text not null,                                   -- no RAB atau no PR
  urutan       int  not null check (urutan >= 1),               -- urutan approver
  approver_npp text not null references karyawan(npp),
  peran        text not null check (peran in ('dept_head_hcis','oad','group_head')),
  keputusan    text not null default 'Menunggu' check (keputusan in ('Menunggu','Disetujui','Ditolak')),
  catatan      text,
  waktu        timestamptz,
  unique (objek, objek_no, urutan),
  check (keputusan <> 'Ditolak' or catatan is not null)         -- catatan wajib jika Ditolak
);

-- DOKUMEN PENGADAAN: PR, PO, GR, Nota Dinas untuk satu RAB (rantai: PO→PR, GR→PO, ND→GR)
create table dokumen_pengadaan (
  id           bigint generated by default as identity primary key,
  jenis        text   not null check (jenis in ('PR','PO','GR','ND')),
  nomor        text   not null,
  rab_id       bigint not null references rab(id) on delete cascade,
  referensi_id bigint references dokumen_pengadaan(id) on delete cascade,
  tanggal      date   not null default current_date,
  nilai        bigint not null check (nilai >= 0),               -- total RAB
  status       text   not null check (status in ('Draft','Menunggu approval','Final')),
  dibuat_oleh  text   not null references karyawan(npp),
  path_storage text,
  unique (jenis, nomor)                                          -- unik per jenis
);

