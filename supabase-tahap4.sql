-- ---------- 3. FUNGSI BANTU UNTUK RLS ----------
-- NPP pengguna yang sedang login (dari email <npp>@jmclick.test di token)
create or replace function auth_npp() returns text
language sql stable security definer set search_path = public as $$
  select case when (auth.jwt() ->> 'email') like '%@jmclick.test'
              then split_part(auth.jwt() ->> 'email', '@', 1) end;
$$;
-- Role pengguna (hanya akun aktif)
create or replace function auth_role() returns text
language sql stable security definer set search_path = public as $$
  select role from akun where npp = auth_npp() and aktif;
$$;
-- HCS (boleh memproses): HCIS, Dept Head HCIS, OAD, Group Head
create or replace function is_hcs() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(auth_role() in ('hcis','dept_head_hcis','oad','group_head'), false);
$$;
-- Staf (boleh melihat semua): HCS + ATA
create or replace function is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(auth_role() in ('hcis','dept_head_hcis','oad','group_head','ata'), false);
$$;
-- Pengajuan / Tiket PP milik pengguna yang login
create or replace function own_pengajuan(p bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from pengajuan_sppd where id = p and npp = auth_npp());
$$;
create or replace function own_tpp(p bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from tiket_pp t join pengajuan_sppd s on s.id = t.pengajuan_id
                 where t.id = p and s.npp = auth_npp());
$$;
-- Tiket PP hanya untuk SPPD milik sendiri yang TIDAK membawa keluarga
create or replace function boleh_tpp(p bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from pengajuan_sppd where id = p and npp = auth_npp() and not bawa_keluarga);
$$;

-- Nomor otomatis (karyawan tidak bisa melihat pengajuan orang lain, jadi nomor dibuat di database)
create or replace function next_no_pengajuan() returns text
language sql stable security definer set search_path = public as $$
  select 'SPPD-MTS-' || extract(year from current_date)::int || '-' ||
         lpad((coalesce(max(right(no_pengajuan,5)::int),0) + 1)::text, 5, '0')
  from pengajuan_sppd where no_pengajuan like 'SPPD-MTS-' || extract(year from current_date)::int || '-%';
$$;
create or replace function next_no_tpp() returns text
language sql stable security definer set search_path = public as $$
  select 'TPP-' || extract(year from current_date)::int || '-' ||
         lpad((coalesce(max(right(no_tpp,5)::int),0) + 1)::text, 5, '0')
  from tiket_pp where no_tpp like 'TPP-' || extract(year from current_date)::int || '-%';
$$;

-- ---------- 4. HAK AKSES ----------
-- Tanpa login (anon) tidak boleh membaca/menulis tabel apa pun.
-- Pengecualian: fungsi reset_demo() untuk tombol "Reset data demo" (lihat supabase-reset-demo.sql).
revoke all on all tables    in schema public from anon;
revoke all on all sequences in schema public from anon;
alter default privileges in schema public revoke all on tables    from anon;
alter default privileges in schema public revoke all on sequences from anon;

grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
-- Kolom yang boleh diubah sendiri: hanya login_terakhir (akun) dan dibaca (notifikasi)
revoke update on akun, notifikasi from authenticated;
grant update (login_terakhir) on akun to authenticated;
grant update (dibaca) on notifikasi to authenticated;

revoke execute on function auth_npp(), auth_role(), is_hcs(), is_staff(), own_pengajuan(bigint),
                           own_tpp(bigint), boleh_tpp(bigint), next_no_pengajuan(), next_no_tpp() from public, anon;
grant execute on function auth_npp(), auth_role(), is_hcs(), is_staff(), own_pengajuan(bigint),
                          own_tpp(bigint), boleh_tpp(bigint), next_no_pengajuan(), next_no_tpp() to authenticated;

-- Hapus semua aturan lama ("proto ...") di schema public
do $$
declare r record;
begin
  for r in select policyname, tablename from pg_policies where schemaname = 'public' loop
    execute format('drop policy %I on %I', r.policyname, r.tablename);
  end loop;
end $$;

