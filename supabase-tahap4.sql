-- Master yang boleh dibaca semua pengguna login
create policy "baca kantor"         on kantor            for select to authenticated using (true);
create policy "baca jarak"          on jarak_kantor      for select to authenticated using (true);
create policy "baca tarif harian"   on tarif_uang_harian for select to authenticated using (true);
create policy "baca tarif inap"     on tarif_penginapan  for select to authenticated using (true);
create policy "baca tarif sewa"     on tarif_sewa        for select to authenticated using (true);
create policy "baca tarif pack"     on tarif_pengepakan  for select to authenticated using (true);

-- Data pribadi: karyawan hanya miliknya sendiri; staf melihat semua
create policy "baca karyawan"   on karyawan   for select to authenticated using (npp = auth_npp() or is_staff());
create policy "baca akun"       on akun       for select to authenticated using (npp = auth_npp() or is_staff());
create policy "ubah login akun" on akun       for update to authenticated using (npp = auth_npp()) with check (npp = auth_npp());
create policy "baca sk"         on sk_mutasi  for select to authenticated using (npp = auth_npp() or is_staff());
create policy "baca keluarga"   on keluarga   for select to authenticated using (npp = auth_npp() or is_staff());

-- Pengajuan SPPD: karyawan mengajukan & melihat miliknya; HCS memproses
create policy "baca sppd"   on pengajuan_sppd for select to authenticated using (npp = auth_npp() or is_staff());
create policy "ajukan sppd" on pengajuan_sppd for insert to authenticated
  with check (npp = auth_npp() and auth_role() = 'karyawan' and status = 'Diajukan' and tahap_hcis = 'Diterima');
create policy "proses sppd" on pengajuan_sppd for update to authenticated using (is_hcs()) with check (is_hcs());
create policy "hapus sppd"  on pengajuan_sppd for delete to authenticated
  using (is_hcs() or (npp = auth_npp() and tahap_hcis = 'Diterima'));   -- batal kirim saat gagal simpan

create policy "baca dokumen"   on dokumen for select to authenticated
  using (is_staff() or own_pengajuan(pengajuan_id) or own_tpp(tpp_id));
create policy "unggah dokumen" on dokumen for insert to authenticated
  with check (is_hcs() or own_pengajuan(pengajuan_id) or own_tpp(tpp_id));
create policy "hapus dokumen"  on dokumen for delete to authenticated using (is_hcs());

create policy "baca peng_kel"   on pengajuan_keluarga for select to authenticated using (is_staff() or own_pengajuan(pengajuan_id));
create policy "tambah peng_kel" on pengajuan_keluarga for insert to authenticated with check (is_hcs() or own_pengajuan(pengajuan_id));
create policy "ubah peng_kel"   on pengajuan_keluarga for update to authenticated using (is_hcs()) with check (is_hcs());
create policy "hapus peng_kel"  on pengajuan_keluarga for delete to authenticated using (is_hcs());

-- Notifikasi: penerima membaca & menandai dibaca; HCS boleh mengirim ke siapa pun
create policy "baca notifikasi"  on notifikasi for select to authenticated using (penerima_npp = auth_npp() or is_staff());
create policy "kirim notifikasi" on notifikasi for insert to authenticated with check (penerima_npp = auth_npp() or is_hcs());
create policy "tandai dibaca"    on notifikasi for update to authenticated using (penerima_npp = auth_npp()) with check (penerima_npp = auth_npp());

-- Riwayat status: hanya bisa ditambah (atas nama sendiri), tidak bisa diubah/dihapus
create policy "baca riwayat" on riwayat_status for select to authenticated
  using (is_staff() or (objek = 'pengajuan_sppd' and own_pengajuan(objek_id)) or (objek = 'tiket_pp' and own_tpp(objek_id)));
create policy "catat riwayat" on riwayat_status for insert to authenticated
  with check (oleh_npp = auth_npp() and (is_hcs() or (objek = 'pengajuan_sppd' and own_pengajuan(objek_id))
                                                  or (objek = 'tiket_pp' and own_tpp(objek_id))));

-- Tiket PP: karyawan (SPPD tanpa keluarga) mengajukan & melihat miliknya; HCS memproses
create policy "baca tpp"   on tiket_pp for select to authenticated using (is_staff() or own_pengajuan(pengajuan_id));
create policy "ajukan tpp" on tiket_pp for insert to authenticated with check (boleh_tpp(pengajuan_id) and status = 'Diajukan');
create policy "proses tpp" on tiket_pp for update to authenticated using (is_hcs()) with check (is_hcs());
create policy "hapus tpp"  on tiket_pp for delete to authenticated
  using (is_hcs() or (own_pengajuan(pengajuan_id) and status = 'Diajukan'));     -- batal kirim saat gagal simpan

-- Proses HCIS (tidak terlihat oleh karyawan): RAB, cek kelengkapan, approval, dokumen pengadaan
create policy "baca rab"         on rab                   for select to authenticated using (is_staff());
create policy "kelola rab"       on rab                   for all    to authenticated using (is_hcs()) with check (is_hcs());
create policy "baca checklist"   on checklist_kelengkapan for select to authenticated using (is_staff());
create policy "kelola checklist" on checklist_kelengkapan for all    to authenticated using (is_hcs()) with check (is_hcs());
create policy "baca approval"    on approval              for select to authenticated using (is_staff());
create policy "kelola approval"  on approval              for all    to authenticated using (is_hcs()) with check (is_hcs());
create policy "baca pengadaan"   on dokumen_pengadaan     for select to authenticated using (is_staff());
create policy "kelola pengadaan" on dokumen_pengadaan     for all    to authenticated using (is_hcs()) with check (is_hcs());
