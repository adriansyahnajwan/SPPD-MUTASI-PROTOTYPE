-- Cara pakai: Supabase > SQL Editor > New query > paste semua > Run
--
-- TPP masuk antrean HCIS yang sama dengan SPPD dan memakai 9 tahap yang sama.
-- - tiket_pp: tahap HCIS + detail tiket yang diisi HCIS (skema dipesankan kantor)
-- - rab_tpp: RAB penggantian tiket PP (2 baris: Pulang & Pergi, tanpa pajak)
-- - dokumen_pengadaan: PR/PO/GR/ND untuk RAB TPP + jenis baru PB
--   (Permohonan Penggantian Biaya <= Rp 50.000.000)
-- - checklist_kelengkapan: checklist untuk Tiket PP
-- Semua data dummy.
-- ============================================================

-- ---------- 1. TIKET_PP: tahap HCIS & detail tiket ----------
alter table tiket_pp add column if not exists tahap_hcis text not null default 'Diterima';
alter table tiket_pp drop constraint if exists tiket_pp_tahap_hcis_check;
alter table tiket_pp add constraint tiket_pp_tahap_hcis_check check (tahap_hcis in
  ('Diterima','Cek kelengkapan','Susun RAB','Approval Dept Head HCIS','Buat PR',
   'Approval OAD & Group Head','Buat PO & GR','Serahkan ke ATA','Diserahkan ke ATA'));
-- Diisi HCIS untuk skema dipesankan kantor (reimburse memakai nominal dari karyawan)
alter table tiket_pp add column if not exists operator_pulang     text;     -- maskapai / operator
alter table tiket_pp add column if not exists rute_pulang         text;
alter table tiket_pp add column if not exists biaya_pulang        bigint check (biaya_pulang >= 0);
alter table tiket_pp add column if not exists operator_pergi      text;
alter table tiket_pp add column if not exists rute_pergi          text;
alter table tiket_pp add column if not exists biaya_pergi         bigint check (biaya_pergi >= 0);
alter table tiket_pp add column if not exists eticket_terbit_pada timestamptz;   -- notifikasi "E-ticket sudah terbit"

-- ---------- 2. RAB_TPP ----------
drop table if exists rab_tpp cascade;
create table rab_tpp (
  id            bigint generated by default as identity primary key,
  no_rab        text   not null unique,                                  -- RAB-TPP-YYYY-NNNN
  tpp_id        bigint not null unique references tiket_pp(id) on delete cascade,   -- 1 TPP = 1 RAB
  angkutan      text   not null check (angkutan in ('Pesawat','Kereta','Bus')),
  kelas         text   not null check (kelas in ('Ekonomi','Eksekutif')),
  rute_pulang   text   not null,
  rute_pergi    text   not null,
  tgl_pulang    date   not null,
  tgl_pergi     date   not null,
  biaya_pulang  bigint not null check (biaya_pulang >= 0),
  biaya_pergi   bigint not null check (biaya_pergi >= 0),
  total         bigint generated always as (biaya_pulang + biaya_pergi) stored,   -- tanpa pajak
  triwulan      int    not null check (triwulan between 1 and 4),
  tahun         int    not null,
  catatan       text,
  dibuat_oleh   text   not null references karyawan(npp),
  dibuat_pada   timestamptz not null default now()
);

-- ---------- 3. DOKUMEN_PENGADAAN: untuk RAB SPPD atau RAB TPP, + jenis PB ----------
alter table dokumen_pengadaan alter column rab_id drop not null;
alter table dokumen_pengadaan add column if not exists rab_tpp_id bigint references rab_tpp(id) on delete cascade;
alter table dokumen_pengadaan drop constraint if exists dokumen_pengadaan_jenis_check;
alter table dokumen_pengadaan add constraint dokumen_pengadaan_jenis_check check (jenis in ('PR','PO','GR','ND','PB'));
alter table dokumen_pengadaan drop constraint if exists dokumen_pengadaan_satu_rab_check;
alter table dokumen_pengadaan add constraint dokumen_pengadaan_satu_rab_check check ((rab_id is null) <> (rab_tpp_id is null));

-- ---------- 4. CHECKLIST_KELENGKAPAN: untuk SPPD atau Tiket PP ----------
alter table checklist_kelengkapan alter column pengajuan_id drop not null;
alter table checklist_kelengkapan add column if not exists tpp_id bigint references tiket_pp(id) on delete cascade;
alter table checklist_kelengkapan drop constraint if exists checklist_kelengkapan_item_check;
alter table checklist_kelengkapan add constraint checklist_kelengkapan_item_check check (item in
  ('form','sk','kk','rekening','sekolah_asal','sekolah_baru',            -- SPPD
   'form_tpp','form_sppd','tiket_pp','tagihan_travel'));                -- Tiket PP (+ sk, kk, rekening)
alter table checklist_kelengkapan drop constraint if exists checklist_kelengkapan_satu_objek_check;
alter table checklist_kelengkapan add constraint checklist_kelengkapan_satu_objek_check check ((pengajuan_id is null) <> (tpp_id is null));
alter table checklist_kelengkapan drop constraint if exists checklist_kelengkapan_tpp_id_item_key;
alter table checklist_kelengkapan add constraint checklist_kelengkapan_tpp_id_item_key unique (tpp_id, item);

-- ---------- 5. HAK AKSES (sama seperti RAB SPPD: hanya staf HCS) ----------
alter table rab_tpp enable row level security;
drop policy if exists "baca rab tpp" on rab_tpp;
drop policy if exists "kelola rab tpp" on rab_tpp;
create policy "baca rab tpp"   on rab_tpp for select to authenticated using (is_staff());
create policy "kelola rab tpp" on rab_tpp for all    to authenticated using (is_hcs()) with check (is_hcs());
revoke all on rab_tpp from anon;
grant select, insert, update, delete on rab_tpp to authenticated;
grant usage, select on all sequences in schema public to authenticated;

notify pgrst, 'reload schema';
